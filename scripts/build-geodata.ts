// Regenerates public/geo/land.geojson (Natural Earth 1:50m land, public domain, naturalearthdata.com) and src/core/lanes.generated.ts.
// Run: bun scripts/build-geodata.ts
import { seaRoute } from 'searoute-ts';
import type { FeatureCollection, MultiPolygon, Polygon, Position } from 'geojson';
import { demoShipments } from '../src/core/demo';
import { portById, portIds, type PortId } from '../src/core/ports';

const round = (value: number, digits: number): number => Math.round(value * 10 ** digits) / 10 ** digits;
const roundPosition = (digits: number) => (position: Position): Position => [round(position[0] ?? 0, digits), round(position[1] ?? 0, digits)];
const roundRings = (digits: number) => (rings: Position[][]): Position[][] => rings.map(ring => ring.map(roundPosition(digits)));

const NATURAL_EARTH = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_50m_land.geojson';
const land = await fetch(NATURAL_EARTH).then(response => response.json()) as FeatureCollection<Polygon | MultiPolygon>;
const quantised: FeatureCollection<Polygon | MultiPolygon> = {
  type: 'FeatureCollection',
  features: land.features.map(item => ({
    ...item, properties: {},
    geometry: item.geometry.type === 'Polygon'
      ? { type: 'Polygon', coordinates: roundRings(2)(item.geometry.coordinates) }
      : { type: 'MultiPolygon', coordinates: item.geometry.coordinates.map(roundRings(2)) },
  })),
};
await Bun.write(new URL('../public/geo/land.geojson', import.meta.url), JSON.stringify(quantised));

/** Every consecutive pair of stops the fleet sails, once, in registry order: the lanes are exactly what the fleet needs. */
const ordered = (a: PortId, b: PortId): readonly [PortId, PortId] => portIds.indexOf(a) <= portIds.indexOf(b) ? [a, b] : [b, a];
const pairs = [...new Map(demoShipments(new Date(0)).flatMap(shipment => {
  const stops = [shipment.origin, ...shipment.via, shipment.destination];
  return stops.slice(1).map((to, index) => ordered(stops[index] as PortId, to));
}).map(pair => [pair.join('>'), pair] as const)).values()];

const point = (id: PortId) => ({ type: 'Feature' as const, properties: {}, geometry: { type: 'Point' as const, coordinates: [...portById.get(id)?.coordinates ?? [0, 0]] } });
const polyline = (from: PortId, to: PortId, route: ReturnType<typeof seaRoute>) =>
  [portById.get(from)?.coordinates, ...route.geometry.coordinates.map(roundPosition(2)).map(([lon, lat]) => [lon, lat] as const), portById.get(to)?.coordinates];
/** A lane that needs Suez or Bab-el-Mandeb also gets its Cape of Good Hope alternative, keyed `a>b#cape`: the Red Sea diversion. */
const lanes = pairs.flatMap(([from, to]) => {
  const shortest = seaRoute(point(from), point(to), { units: 'kilometers' });
  const cape = seaRoute(point(from), point(to), { units: 'kilometers', restrictions: ['suez', 'babelmandeb'] });
  return [
    [`${from}>${to}`, polyline(from, to, shortest)] as const,
    ...(cape.properties.length > shortest.properties.length * 1.01 ? [[`${from}>${to}#cape`, polyline(from, to, cape)] as const] : []),
  ];
});

const header = `// Generated by scripts/build-geodata.ts; do not edit.
// Sea lanes: shortest paths over the Eurostat SeaRoute maritime network (marnet 100 km, v3.5), computed with
// searoute-ts (MIT, github.com/mayurrawte/searoute-ts). The network derives from the Oak Ridge National Laboratory
// Global Shipping Lane Network (World, 2000), enriched by Eurostat from AIS data; github.com/eurostat/searoute
// (EUPL-1.2). A '#cape' key is the same pair with Suez and Bab-el-Mandeb closed. Illustrative lanes only, not for navigation.
`;
const body = `export const seaLanes: Readonly<Record<string, readonly (readonly [number, number])[]>> = ${JSON.stringify(Object.fromEntries(lanes))};\n`;
await Bun.write(new URL('../src/core/lanes.generated.ts', import.meta.url), header + body);
console.log(`${lanes.length} lanes, ${(header + body).length} bytes`);
