// Regenerates public/geo/land.geojson (Natural Earth 1:50m land, public domain, naturalearthdata.com) and src/sea-lanes.ts.
// Run: bun src/client/geo/build-geodata.ts
import { seaRoute } from 'searoute-ts';
import type { FeatureCollection, MultiPolygon, Polygon, Position } from 'geojson';
import { ports } from '../../domain';

const round = (value: number, digits: number): number => Math.round(value * 10 ** digits) / 10 ** digits;
const roundPosition = (digits: number) => (position: Position): Position => [round(position[0] ?? 0, digits), round(position[1] ?? 0, digits)];
const roundRings = (digits: number) => (rings: Position[][]): Position[][] => rings.map(ring => ring.map(roundPosition(digits)));

if (!Bun.argv.includes('--lanes-only')) {
const NATURAL_EARTH = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_50m_land.geojson';
const land = await fetch(NATURAL_EARTH).then(response => response.json()) as FeatureCollection<Polygon | MultiPolygon>;
const quantised: FeatureCollection<Polygon | MultiPolygon> = {
  type: 'FeatureCollection',
  features: land.features.map(item => ({
    ...item, properties: {},
    geometry: item.geometry.type === 'Polygon'
      ? { type: 'Polygon', coordinates: roundRings(2)(item.geometry.coordinates) }
      : { type: 'MultiPolygon', coordinates: item.geometry.coordinates.map(roundRings(2)) },
  })),
};
await Bun.write(new URL('../../../public/geo/land.geojson', import.meta.url), JSON.stringify(quantised));
}

const point = (coordinates: readonly [number, number]) => ({ type: 'Feature' as const, properties: {}, geometry: { type: 'Point' as const, coordinates: [...coordinates] } });
const pairs = ports.flatMap((from, index) => ports.slice(index + 1).map(to => [from, to] as const));
const lanes = pairs.map(([from, to]) => {
  const route = seaRoute(point(from.coordinates), point(to.coordinates));
  const body = route.geometry.coordinates.map(roundPosition(2)).map(([lon, lat]) => [lon, lat] as const);
  return [`${from.id}>${to.id}`, [from.coordinates, ...body, to.coordinates]] as const;
});

const header = `// Generated by src/client/geo/build-geodata.ts; do not edit.
// Sea lanes: shortest paths over the Eurostat SeaRoute maritime network (marnet 100 km, v3.5), computed with
// searoute-ts (MIT, github.com/mayurrawte/searoute-ts). The network derives from the Oak Ridge National Laboratory
// Global Shipping Lane Network (World, 2000), enriched by Eurostat from AIS data; github.com/eurostat/searoute
// (EUPL-1.2). Illustrative lanes only, not for navigation.
`;
const body = `export const seaLanes: Readonly<Record<string, readonly (readonly [number, number])[]>> = ${JSON.stringify(Object.fromEntries(lanes))};\n`;
await Bun.write(new URL('../../sea-lanes.ts', import.meta.url), header + body);
console.log(lanes.map(([key, line]) => `${key}: ${line.length} pts`).join('\n'));
